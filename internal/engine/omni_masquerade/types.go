package omni_masquerade

import (
	"time"
)

// TargetSeed represents the initial clue (e.g. username) provided to the Omni-Masquerade engine.
type TargetSeed struct {
	Username  string            `json:"username" yaml:"username"`
	SeedType  string            `json:"seed_type" yaml:"seed_type"` // e.g., "username", "email", "domain"
	Metadata  map[string]string `json:"metadata" yaml:"metadata"`
	Timestamp time.Time         `json:"timestamp" yaml:"timestamp"`
}

// EnrichedProfile represents a fully verified profile discovered across providers.
type EnrichedProfile struct {
	Platform    string            `json:"platform" yaml:"platform"`
	ProfileURL  string            `json:"profile_url" yaml:"profile_url"`
	Username    string            `json:"username" yaml:"username"`
	Exists      bool              `json:"exists" yaml:"exists"`
	Confidence  float64           `json:"confidence" yaml:"confidence"`
	RawMetadata map[string]string `json:"raw_metadata" yaml:"raw_metadata"`
	DiscoveredAt time.Time        `json:"discovered_at" yaml:"discovered_at"`
}

// IntelligenceDatabase represents the consolidated real-world OSINT database record generated by the engine.
type IntelligenceDatabase struct {
	SeedID         string                       `json:"seed_id" yaml:"seed_id"`
	PrimaryUsername string                      `json:"primary_username" yaml:"primary_username"`
	Profiles       []EnrichedProfile            `json:"profiles" yaml:"profiles"`
	SecondaryPivots map[string][]string         `json:"secondary_pivots" yaml:"secondary_pivots"` // e.g. emails, pgp keys, crypto wallets
	GraphNodes     int                          `json:"graph_nodes" yaml:"graph_nodes"`
	GraphEdges     int                          `json:"graph_edges" yaml:"graph_edges"`
	GeneratedAt    time.Time                    `json:"generated_at" yaml:"generated_at"`
}

// EngineConfig holds configuration parameters for the Omni-Masquerade execution pipeline.
type EngineConfig struct {
	MaxWorkers    int           `json:"max_workers" yaml:"max_workers"`
	Timeout       time.Duration `json:"timeout" yaml:"timeout"`
	EnableBrowser bool          `json:"enable_browser" yaml:"enable_browser"`
	StealthMode   bool          `json:"stealth_mode" yaml:"stealth_mode"`
}
